# Папка с входящими письмами, которую ожидает приложение.
INBOX="inbox"

# 1) Проверка существования директории (пример прямо из ТЗ).
#    [ -d "$INBOX" ] -> "директория существует?"; ! -> отрицание.
if [ ! -d "$INBOX" ]; then
    echo "ERROR: папка '$INBOX' не найдена. Запусти скрипт из корня проекта."
    exit 1            # выход с ненулевым кодом = "провал"
fi

# 2) Проверка, что в системе есть python3 (иначе запускать нечего).
#    command -v ищет программу; >/dev/null 2>&1 прячет её вывод.
if ! command -v python3 >/dev/null 2>&1; then
    echo "ERROR: python3 не установлен или не в path."
    exit 1
fi

# 3) Запуск приложения. "$@" пробрасывает аргументы дальше,
#    чтобы работало и ./run.example.sh --dry-run.
#    | tee run.log  -> печатает на экран И дублирует в файл run.log.
echo "Запуск..."
python3 sorter.py "$@" | tee run.log

# 4) Берём код возврата python3.
#    При конвейере (|) $? вернул бы код tee, поэтому PIPESTATUS[0].
status=${PIPESTATUS[0]}

# 5) Вывод итогового статуса по коду возврата.
#    -eq -> сравнение чисел ("равно").
if [ "$status" -eq 0 ]; then
    echo "READY: обработка завершена успешно. Лог сохранён в run.log"
else
    echo "Обработка завершилась с ошибкой (код $status). Подробности в run.log"
    exit "$status"
fi
