"""
Три фичи с ГигаЧатом поверх базовой системы.

Каждая функция получает уже прочитанное письмо (объект EmailMessage из основного
проекта) и клиента ГигаЧата. То есть фичи работают поверх классификации —
сначала база читает и сортирует письма, потом ИИ их обогащает.

  1. extract_tasks   — найти в письме обещания со сроком (поставить задачу);
  2. check_phishing  — оценить, похоже ли письмо на обман/фишинг;
  3. draft_reply     — сгенерировать черновик ответа на письмо.
"""


def extract_tasks(email, client):
    """Найти в письме обещание/задачу со сроком."""
    prompt = (
        "Прочитай письмо. Если в нём есть обещание что-то сделать к сроку, "
        "коротко опиши задачу и срок. Если нет — ответь, что задач нет.\n\n"
        "Тема: " + email.subject + "\n"
        "Текст: " + email.body
    )
    return client.ask(prompt, kind="task")


def check_phishing(email, client):
    """Оценить, похоже ли письмо на фишинг или социальную инженерию."""
    prompt = (
        "Это письмо может быть обманом (фишинг, социнженерия)? "
        "Ответь ДА или НЕТ и одно короткое предложение почему.\n\n"
        "Отправитель: " + email.sender + "\n"
        "Тема: " + email.subject + "\n"
        "Текст: " + email.body
    )
    return client.ask(prompt, kind="phishing")


def draft_reply(email, client):
    """Сгенерировать черновик ответа на письмо (для поддержки)."""
    prompt = (
        "Напиши короткий вежливый черновик ответа от IT-поддержки на это письмо.\n\n"
        "Тема: " + email.subject + "\n"
        "Текст: " + email.body
    )
    return client.ask(prompt, kind="reply")
